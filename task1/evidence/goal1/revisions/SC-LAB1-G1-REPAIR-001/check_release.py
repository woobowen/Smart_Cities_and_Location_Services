"""Task-local release audit. No model calls, installation, or original-file mutation."""
from pathlib import Path
import datetime
import hashlib
import json
import re
import subprocess
import urllib.parse
import zipfile

ROOT = next(p for p in Path(__file__).resolve().parents if (p / 'AGENTS.md').exists())
REV = Path(__file__).resolve().parent
BASE = 'c2e3ffe2f5af92ee03dac16a2865ec7c42f576e0'
CODE = '880290a5dada84c711248844038daa3ee35eeefb'


def git(*args):
    return subprocess.check_output(['git', *args], cwd=ROOT)


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def save(name, value):
    (REV / name).write_text(json.dumps(value, ensure_ascii=False, indent=2) + '\n')


protected = json.loads((REV / 'protected_integrity.json').read_text())
for name, item in protected['files'].items():
    item['actual'] = digest(ROOT / name) if (ROOT / name).is_file() else None
    item['unchanged'] = item['actual'] == item['expected']
protected['status'] = 'PASS' if all(x['unchanged'] for x in protected['files'].values()) else 'FAIL'
save('protected_integrity.json', protected)

changed = set(git('diff', '--name-only', '-z', BASE).decode().split('\0'))
changed.update(git('ls-files', '--others', '--exclude-standard', '-z').decode().split('\0'))
changed.update(str(p.relative_to(ROOT)) for p in (REV / 'handoff').rglob('*.log'))
changed.discard('')
changed.discard(str((REV / 'file_manifest.json').relative_to(ROOT)))
changed.discard(str((REV / 'release_check.json').relative_to(ROOT)))
paths = [ROOT / p for p in sorted(changed)]
missing = [str(p.relative_to(ROOT)) for p in paths if not p.is_file()]
large = [str(p.relative_to(ROOT)) for p in paths if p.is_file() and p.stat().st_size >= 90 * 1024 * 1024]
symlinks = [str(p.relative_to(ROOT)) for p in paths if p.is_symlink()]

patterns = {
    'private_key': re.compile(rb'-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----'),
    'api_key': re.compile(rb'\bsk-(?:proj-|svcacct-)?[A-Za-z0-9_-]{24,}'),
    'jwt': re.compile(rb'\beyJ[A-Za-z0-9_-]{12,}\.[A-Za-z0-9_-]{20,}\.[A-Za-z0-9_-]{20,}'),
    'credential_in_url': re.compile(rb'https?://[^\s/<>"\x27:]+:[^\s/<>"\x27@]+@'),
}
findings = []
text_paths = []
absolute_paths = []
scanned_zip_members = 0


def scan(label, raw):
    for kind, pattern in patterns.items():
        if pattern.search(raw):
            findings.append({'path': label, 'kind': kind})


for path in paths:
    if not path.is_file():
        continue
    name = str(path.relative_to(ROOT))
    data = path.read_bytes()
    scan(name, data)
    if path.suffix == '.zip':
        with zipfile.ZipFile(path) as archive:
            for info in archive.infolist():
                if not info.is_dir():
                    scan(name + '::' + info.filename, archive.read(info))
                    scanned_zip_members += 1
    try:
        text = data.decode('utf-8')
    except UnicodeDecodeError:
        continue
    text_paths.append(name)
    if re.search(r'/(?:home|tmp|mnt|usr|opt)/', text):
        absolute_paths.append(name)

active_markdown = [p for p in paths if p.suffix == '.md'
                   and '/handoff/' not in str(p)
                   and '/docs/research/' not in str(p)
                   and not p.name.startswith('historical_')]
broken = []
links_checked = 0
for path in active_markdown:
    content = re.sub(r'```.*?```', '', path.read_text(), flags=re.S)
    for target in re.findall(r'\[[^\]]*\]\(([^)]+)\)', content):
        target = target.strip().strip('<>')
        url = urllib.parse.urlsplit(target)
        if url.scheme or not url.path:
            continue
        local = (path.parent / urllib.parse.unquote(url.path)).resolve()
        links_checked += 1
        # These audit outputs are generated by this same command below.
        if local in {REV / 'file_manifest.json', REV / 'release_check.json'}:
            continue
        if not local.exists():
            broken.append({'file': str(path.relative_to(ROOT)), 'target': target})

bound = {}
for name in ['validation.json', 'live_audit.json', 'notebooks.json', 'results/manifest.json']:
    obj = json.loads((REV / name).read_text())
    bound[name] = {
        'recorded_code_sha': obj.get('code_sha'),
        'code_matches': obj.get('code_sha') == CODE,
        'source_mismatches': [p for p, sha in obj.get('source_hashes', {}).items() if digest(ROOT / p) != sha],
    }
code_changed = git('diff', CODE, '--', 'task1/workflow', 'task1/tests', 'task1/scripts', 'task1/config').decode()
notebooks = []
for execution in json.loads((REV / 'notebooks.json').read_text())['executions']:
    path = ROOT / execution['notebook']
    notebook = json.loads(path.read_text())
    cells = [cell for cell in notebook['cells'] if cell['cell_type'] == 'code']
    errors = sum(output.get('output_type') == 'error' for cell in cells for output in cell.get('outputs', []))
    counts = [cell.get('execution_count') for cell in cells]
    notebooks.append({'path': execution['notebook'], 'hash_matches': digest(path) == execution['sha256'],
                      'code_cells': len(cells), 'execution_counts': counts, 'output_errors': errors,
                      'new_model_calls': execution['new_model_calls'],
                      'passed': errors == 0 and counts == list(range(1, len(cells) + 1))})

# Preserve handoff/historical logs and generated patch/SVG byte-for-byte.
# Git patches use a literal space for unchanged blank lines; Matplotlib emits SVG path whitespace.
exempt = [str(p.relative_to(ROOT)) for p in paths if '/handoff/' in str(p)
          or '/docs/research/' in str(p) or p.name.startswith('historical_')
          or p.name in {'tests_development_01.txt', 'tests_development_01.xml', 'code_repair.diff', 'pilot_diagnostics.svg'}]
diff_args = ['git', 'diff', '--check', BASE, '--', '.', *[':(exclude)' + p for p in exempt]]
diff = subprocess.run(diff_args, cwd=ROOT, text=True, capture_output=True)
checks = {'protected_files': protected['status'] == 'PASS', 'no_missing_files': not missing,
          'no_large_files': not large, 'no_symlinks': not symlinks,
          'secret_patterns_clear': not findings, 'active_local_links_exist': not broken,
          'code_unchanged_since_final_run': not code_changed,
          'bound_sources_match': all(x['code_matches'] and not x['source_mismatches'] for x in bound.values()),
          'notebook_outputs_match_execution_records': all(x['passed'] and x['hash_matches'] for x in notebooks),
          'diff_check': diff.returncode == 0}
record = {'at': datetime.datetime.now(datetime.timezone.utc).isoformat(),
          'code_sha': CODE, 'audit_base': BASE, 'status': 'PASS' if all(checks.values()) else 'FAIL',
          'checks': checks, 'protected_count': len(protected['files']),
          'scanned_files': len(paths), 'zip_members_scanned': scanned_zip_members,
          'secret_pattern_findings': findings, 'secret_scan_scope': 'Pattern scan of every changed/new file and handoff ZIP member; no claim of exhaustive credential detection.',
          'missing_files': missing, 'large_files': large, 'symlinks': symlinks,
          'links_checked': links_checked, 'broken_links': broken,
          'markdown_scope': 'Active changed Markdown only. Verbatim handoff/research/historical copies retain their original link bases.',
          'absolute_path_files': absolute_paths,
          'absolute_path_review': 'Historical evidence, actual command/version/cwd receipts, pinned temporary CLI, environment restoration and local paths are intentional. Runtime data paths remain project-relative. No auth/account file content included.',
          'bound_sources': bound, 'notebooks': notebooks,
          'diff_check_exit': diff.returncode, 'diff_check_output': diff.stdout + diff.stderr,
          'verbatim_whitespace_exemptions': exempt,
          'self_reference_policy': 'file_manifest.json excludes itself. release_check.json is included in the manifest after this check is written.'}
save('release_check.json', record)
changed.add(str((REV / 'release_check.json').relative_to(ROOT)))
initial = json.loads((REV / 'initial_files.json').read_text())['hashes']
manifest = []
for name in sorted(changed):
    path = ROOT / name
    manifest.append({'path': name, 'action': 'MODIFIED' if name in initial else 'ADDED',
                     'size': path.stat().st_size if path.is_file() else None,
                     'sha256': digest(path) if path.is_file() else None})
save('file_manifest.json', {'audit_base': BASE, 'code_sha': CODE, 'files': manifest,
     'excluded_self': str((REV / 'file_manifest.json').relative_to(ROOT)),
     'deleted_files': missing, 'scope': 'Files added or changed in this repair relative to the audit base, including explicit preserved handoff logs.'})
print(json.dumps({'status': record['status'], 'checks': checks, 'files': len(manifest),
                  'protected': record['protected_count'], 'secret_findings': findings,
                  'broken_links': broken, 'diff_output': record['diff_check_output']}, ensure_ascii=False, indent=2))
raise SystemExit(0 if record['status'] == 'PASS' else 1)
